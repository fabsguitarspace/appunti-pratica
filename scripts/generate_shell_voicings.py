def source(stem,title,chords):
 diagrams=[];tokens=[]
 for i,c in enumerate(chords):
  tag=f'diag{chr(65+i)}';by_string={s:f for s,f,p in c['voices']}
  items=' '.join(f'(place-fret {s} {by_string[s]})' if s in by_string else f'(mute {s})' for s in range(6,0,-1))
  diagrams.append(rf'''{tag} = \markup \center-column {{ \small "{c['label']}"
  \fret-diagram-verbose #'({items}) }}''')
  notes=[]
  for s,f,p in c['voices']:
   shift=p//12-4
   marks="'"*shift if shift>=0 else ','*(-shift)
   notes.append(f'{NAMES[p%12]}{marks}\\{s}')
  tokens.append('<'+' '.join(notes)+f'>1^\\{tag}')
 return rf"""% Generated by scripts/generate_shell_voicings.py; edit the generator.
\version "2.26.0"
\language "english"
\header {{ title = "{title}" tagline = ##f }}
\paper {{ page-breaking = #ly:one-page-breaking line-width = 160\mm ragged-right = ##f }}
{chr(10).join(diagrams)}
melody = \absolute {{ \time 4/4 \key c \major
 {' | '.join(tokens)} \bar "|." }}
\score {{
 \new StaffGroup <<
  \new Staff {{ \clef "treble_8" \tempo 4 = 60 \melody }}
  \new TabStaff {{ \set TabStaff.stringTunings = #guitar-tuning \omit TextScript \melody }}
 >>
 \layout {{ indent = 0 system-count = #{2 if len(chords)>4 else 1}
  \context {{ \Voice \override TextScript.staff-padding = #4 }}
  \context {{ \Score \omit StringNumber }} }}
}}
\score {{ \new Staff {{ \tempo 4 = 60 c'''4\p c''' c''' c''' \melody }} \midi {{ }} }}
"""

def main():
 for stem,title,chords in SHEETS:
  (ROOT/'src/lilypond'/f'{stem}.ly').write_text(source(stem,title,chords))
 print(f'Generated {len(SHEETS)} three-voice shell examples.')

if __name__=='__main__':main()
