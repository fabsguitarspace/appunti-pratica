#!/usr/bin/env python3
"""Deterministic original bass/percussion samples in a small SoundFont overlay.

No third-party audio samples. Program 33/bank 0: bass; program 0/bank 128:
GM kick 36, snare 38, closed hat 42, ride 51. Overlay leaves guitar preset 0
untouched. Uses standard-library DSP and the SoundFont 2 format.
"""
from pathlib import Path
import math,random,struct,array
ROOT=Path(__file__).resolve().parents[1]
RATE=22050

def chunk(tag,data):return tag+struct.pack('<I',len(data))+data+(b'\0' if len(data)%2 else b'')
def group(kind,*chunks):return chunk(b'LIST',kind+b''.join(chunks))
def name(s):return s.encode('ascii')[:19].ljust(20,b'\0')
def sample(kind,seconds):
 rng=random.Random(187+len(kind));values=[];last=0
 for i in range(int(RATE*seconds)):
  t=i/RATE;attack=min(1,t/.003)
  if kind=='bass':
   f=65.406391;v=(math.sin(2*math.pi*f*t)+.32*math.sin(4*math.pi*f*t)+.12*math.sin(6*math.pi*f*t))*math.exp(-t*1.8)*.55
  elif kind=='kick':
   phase=2*math.pi*(48*t+90*.028*(1-math.exp(-t/.028)))
   v=math.sin(phase)*math.exp(-t*11)*.85
  else:
   noise=rng.uniform(-1,1);high=noise-last;last=noise
   if kind=='snare':v=(.52*high+.30*math.sin(2*math.pi*180*t))*math.exp(-t*19)*.55
   elif kind=='hat':v=high*math.exp(-t*55)*.30
   else:v=(high*.4+math.sin(2*math.pi*3211*t)*.2+math.sin(2*math.pi*4877*t)*.15)*math.exp(-t*8)*.30
  values.append(max(-32767,min(32767,round(v*attack*32767))))
 out=array.array('h',values)
 import sys
 if sys.byteorder!='little':out.byteswap()
 return out.tobytes()

def build():
 samples=[('bass',36,3.0),('kick',36,.6),('snare',38,.35),('hat',42,.14),('ride',51,.9)]
 pcm=b'';headers=[];offset=0
 for label,key,length in samples:
  data=sample(label,length);size=len(data)//2
  headers.append(struct.pack('<20sIIIIIBbHH',name(label),offset,offset+size,offset+1,offset+size-1,RATE,key,0,0,1))
  pcm+=data+b'\0'*92;offset+=size+46
 headers.append(struct.pack('<20sIIIIIBbHH',name('EOS'),offset,offset,offset,offset,RATE,0,0,0,1))
 phdr=b''.join(struct.pack('<20sHHHIII',name(n),preset,bank,bag,0,0,0) for n,preset,bank,bag in [('Practice bass',33,0,0),('Practice drums',0,128,1),('EOP',0,0,2)])
 pbag=b''.join(struct.pack('<HH',n,0) for n in (0,1,2))
 pgen=struct.pack('<HHHHHH',41,0,41,1,0,0)
 inst=b''.join(struct.pack('<20sH',name(n),bag) for n,bag in [('Bass',0),('Drums',1),('EOI',5)])
 gens=[];bags=[]
 for i,(label,key,length) in enumerate(samples):
  bags.append(struct.pack('<HH',len(gens),0))
  low,high=(0,127) if i==0 else (key,key)
  gens.append(struct.pack('<HH',43,low+(high<<8)))
  gens.append(struct.pack('<HH',58,key))
  gens.append(struct.pack('<Hh',38,-3600))
  gens.append(struct.pack('<HH',53,i))
 bags.append(struct.pack('<HH',len(gens),0));gens.append(struct.pack('<HH',0,0))
 info=group(b'INFO',chunk(b'ifil',struct.pack('<HH',2,1)),chunk(b'isng',b'EMU8000\0'),chunk(b'INAM',b'Appunti original rhythm\0'),chunk(b'ICMT',b'Original synthesized bass and percussion; generated by generate_rhythm_soundfont.py\0'))
 sdta=group(b'sdta',chunk(b'smpl',pcm))
 pdta=group(b'pdta',chunk(b'phdr',phdr),chunk(b'pbag',pbag),chunk(b'pmod',b'\0'*10),chunk(b'pgen',pgen),chunk(b'inst',inst),chunk(b'ibag',b''.join(bags)),chunk(b'imod',b'\0'*10),chunk(b'igen',b''.join(gens)),chunk(b'shdr',b''.join(headers)))
 body=b'sfbk'+info+sdta+pdta
 return b'RIFF'+struct.pack('<I',len(body))+body

if __name__=='__main__':
 target=ROOT/'src/lilypond/sf/PracticeRhythm.sf2';target.write_bytes(build());print(target.name,target.stat().st_size,'bytes')
